export function isRegistredEnumType(type, references) {
  if (references != null && references?.length > 0) {
    // find name in references
    const ref = references.find((reference) => reference.name === type.split(' | ')[0]);
    if (ref) {
      if (enums.has(`${ref.package}/${ref.module}`)) {
        return true;
      } else {
          console.log(`${ref.package}/${ref.module}`);
        return false;
      }
    } else {
      return false;
    }
  }
  return false;
}
